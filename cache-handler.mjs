/**
 * Response cache of the server: the build's pages, read-only, and the pages
 * rendered since, on a writable disk.
 *
 * Most pages are no longer generated at build time (src/lib/prerender.ts):
 * they are rendered on their first request and must then be kept, or every
 * visit would render them again. Next's own cache writes them next to the
 * build output, in `.next/server`, which the container mounts read-only; it
 * kept them in memory only (50 MB, least recently used first), so a crawler
 * walking the site rendered most pages again and again.
 *
 * This handler stacks two instances of Next's file system cache:
 *
 * - `built` reads the pages generated by the build, where Next left them,
 *   and never writes;
 * - `rendered` keeps every page rendered since in `.next/cache/pages/<build
 *   id>/`, the writable volume of the container (docker-compose.yml), and is
 *   read first, so a page regenerated after the build wins over its seed.
 *
 * Both share Next's in-memory cache in front of the disk. The folder is
 * named after the build: a new deployment starts with an empty one, and the
 * folders of previous builds are deleted on start.
 */
import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(import.meta.url);
const FileSystemCache = require("next/dist/server/lib/incremental-cache/file-system-cache.js").default;

let pruned = false;

/** Deletes the folders of the builds before this one, once per process. */
function prune(root, build) {
  if (pruned) return;
  pruned = true;
  if (!existsSync(root)) return;
  for (const name of readdirSync(root)) {
    if (name !== build) rmSync(join(root, name), { recursive: true, force: true });
  }
}

export default class CacheHandler {
  constructor(context) {
    this.built = new FileSystemCache({ ...context, flushToDisk: false });
    // During the build, pages are written by the build itself: nothing to keep.
    const building = process.env.NEXT_PHASE === "phase-production-build";
    if (context.dev || building || !context.serverDistDir) return;
    const build = readFileSync(join(context.serverDistDir, "..", "BUILD_ID"), "utf8").trim();
    const root = join(context.serverDistDir, "..", "cache", "pages");
    prune(root, build);
    this.rendered = new FileSystemCache({ ...context, serverDistDir: join(root, build), flushToDisk: true });
  }

  async get(key, context) {
    return (await this.rendered?.get(key, context)) ?? this.built.get(key, context);
  }

  async set(key, data, context) {
    return (this.rendered ?? this.built).set(key, data, context);
  }

  async revalidateTag(tags, durations) {
    // The tags manifest is shared by every instance.
    return this.built.revalidateTag(tags, durations);
  }

  resetRequestCache() {}
}
