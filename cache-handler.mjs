/**
 * Response cache of the server: the build's pages, read-only, and the pages
 * rendered since, on a writable disk.
 *
 * Most pages are no longer generated at build time (src/lib/prerender.ts):
 * they are rendered on their first request and must then be kept, or every
 * visit would render them again. Next's own cache writes them next to the
 * build output, in `.next/server`, which the container mounts read-only; it
 * kept them in memory only (50 MB, least recently used first), so a crawler
 * walking the site rendered most pages again and again.
 *
 * This handler stacks two instances of Next's file system cache:
 *
 * - `built` reads the pages generated by the build, where Next left them,
 *   and never writes to disk (its entries go to Next's in-memory cache);
 * - `rendered` keeps the pages rendered since in `.next/cache/pages/<build
 *   id>/`, the writable volume of the container (docker-compose.yml), and is
 *   read first, so a page regenerated after the build wins over its seed.
 *
 * The disk is written by anyone who requests an address, so what reaches it
 * is restricted and bounded:
 *
 * - only successful page and route responses: a 404 (an unknown slug, a
 *   made-up page number) or an error is kept in memory only, so a bot
 *   requesting endless made-up addresses never writes a byte;
 * - fetch results stay in memory too (they would land outside the build's
 *   folder, and nothing would ever delete them);
 * - the store is capped in bytes and in entries (`PAGE_CACHE_MAX_BYTES`,
 *   `PAGE_CACHE_MAX_ENTRIES`; 2 GB and 50,000 by default). Past either, the
 *   least recently used pages are deleted until the store is back under 90 %
 *   of the cap; a deleted page is simply rendered again on its next request.
 *
 * The folder is named after the build: a new deployment starts with an empty
 * one, and the folders of previous builds are deleted on start.
 */
import * as fs from "node:fs";
import * as fsAsync from "node:fs/promises";
import { createRequire } from "node:module";
import * as nodePath from "node:path";

const require = createRequire(import.meta.url);
const FileSystemCache = require("next/dist/server/lib/incremental-cache/file-system-cache.js").default;

/*
 * File system calls on paths only known at run time. Without the ignore
 * comment, the build's file tracing cannot tell which files they reach and
 * copies the whole project into the standalone output.
 */
const existsSync = (path) => fs.existsSync(/* turbopackIgnore: true */ path);
const readdirSync = (path, options) => fs.readdirSync(/* turbopackIgnore: true */ path, options);
const readFileSync = (path, encoding) => fs.readFileSync(/* turbopackIgnore: true */ path, encoding);
const statSync = (path) => fs.statSync(/* turbopackIgnore: true */ path);
const rmSync = (path, options) => fs.rmSync(/* turbopackIgnore: true */ path, options);
const rm = (path, options) => fsAsync.rm(/* turbopackIgnore: true */ path, options);
const join = (...parts) => nodePath.join(/* turbopackIgnore: true */ ...parts);

const GB = 1024 ** 3;
/** Kinds of entries written to disk: rendered responses only. */
const PERSISTED = new Set(["APP_PAGE", "APP_ROUTE", "PAGES"]);
/** Files Next writes for one response, next to its base path. */
const SUFFIXES = [".html", ".rsc", ".meta", ".body", ".json"];
const SEGMENTS = ".segments";

/** A positive number read from the environment, or the default. */
function limit(name, fallback) {
  const value = Number(process.env[name]);
  return Number.isFinite(value) && value > 0 ? value : fallback;
}

/** Size on disk of a folder, recursively. */
function sizeOf(path) {
  let total = 0;
  for (const entry of readdirSync(path, { withFileTypes: true })) {
    const child = join(path, entry.name);
    total += entry.isDirectory() ? sizeOf(child) : statSync(child).size;
  }
  return total;
}

/** Bytes a response takes once written: its body, payloads and metadata. */
function bytesOf(data) {
  let total = 1024;
  if (typeof data.html === "string") total += Buffer.byteLength(data.html);
  if (data.rscData) total += data.rscData.length;
  if (data.body) total += data.body.length ?? Buffer.byteLength(String(data.body));
  if (data.pageData) total += Buffer.byteLength(JSON.stringify(data.pageData));
  for (const buffer of data.segmentData?.values() ?? []) total += buffer.length;
  return total;
}

/**
 * The pages kept on disk, by base path (the response's path without its
 * suffix), least recently used first: a Map keeps its insertion order, and a
 * page read or written again is moved to the end.
 */
class Store {
  constructor(root, maxBytes, maxEntries) {
    this.root = root;
    this.maxBytes = maxBytes;
    this.maxEntries = maxEntries;
    this.entries = new Map();
    this.bytes = 0;
    this.load();
  }

  /** Pages left by a previous process of the same build, oldest first. */
  load() {
    if (!existsSync(this.root)) return;
    const found = [];
    const visit = (dir) => {
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const path = join(dir, entry.name);
        if (entry.isDirectory()) {
          if (!entry.name.endsWith(SEGMENTS)) visit(path);
        } else if (entry.name.endsWith(".meta")) {
          const base = path.slice(0, -".meta".length);
          let bytes = 0;
          for (const suffix of SUFFIXES) if (existsSync(base + suffix)) bytes += statSync(base + suffix).size;
          if (existsSync(base + SEGMENTS)) bytes += sizeOf(base + SEGMENTS);
          found.push({ base, bytes, time: statSync(path).mtimeMs });
        }
      }
    };
    visit(this.root);
    found.sort((a, b) => a.time - b.time);
    for (const { base, bytes } of found) this.entries.set(base, bytes);
    this.bytes = found.reduce((n, e) => n + e.bytes, 0);
  }

  touch(base) {
    const bytes = this.entries.get(base);
    if (bytes === undefined) return;
    this.entries.delete(base);
    this.entries.set(base, bytes);
  }

  /** Records a page just written, then deletes the oldest past the cap. */
  async add(base, bytes) {
    this.bytes -= this.entries.get(base) ?? 0;
    this.entries.delete(base);
    this.entries.set(base, bytes);
    this.bytes += bytes;
    if (this.bytes <= this.maxBytes && this.entries.size <= this.maxEntries) return;
    const removals = [];
    for (const [old, size] of this.entries) {
      if (this.bytes <= this.maxBytes * 0.9 && this.entries.size <= this.maxEntries * 0.9) break;
      this.entries.delete(old);
      this.bytes -= size;
      removals.push(old);
    }
    await Promise.all(removals.map((old) => remove(old)));
  }
}

async function remove(base) {
  await Promise.all(
    [...SUFFIXES, SEGMENTS].map((suffix) => rm(base + suffix, { recursive: true, force: true })),
  );
}

const builds = new Map();

/** The build id of a `.next/server` folder, read once. */
function buildOf(dist) {
  if (!builds.has(dist)) builds.set(dist, readFileSync(join(dist, "..", "BUILD_ID"), "utf8").trim());
  return builds.get(dist);
}

const pruned = new Set();

/** Deletes the folders of the builds before this one, once per process. */
function prune(root, build) {
  if (pruned.has(root)) return;
  pruned.add(root);
  if (!existsSync(root)) return;
  for (const name of readdirSync(root)) {
    if (name !== build) rmSync(join(root, name), { recursive: true, force: true });
  }
}

export default class CacheHandler {
  /** One store per folder, shared by every handler: Next creates one per request. */
  static stores = new Map();

  constructor(context) {
    this.built = new FileSystemCache({ ...context, flushToDisk: false });
    // During the build, pages are written by the build itself: nothing to keep.
    const building = process.env.NEXT_PHASE === "phase-production-build";
    if (context.dev || building || !context.serverDistDir) return;
    const build = buildOf(context.serverDistDir);
    const root = join(context.serverDistDir, "..", "cache", "pages");
    prune(root, build);
    this.rendered = new FileSystemCache({ ...context, serverDistDir: join(root, build), flushToDisk: true });
    const folder = join(root, build);
    if (!CacheHandler.stores.has(folder)) {
      CacheHandler.stores.set(
        folder,
        new Store(folder, limit("PAGE_CACHE_MAX_BYTES", 2 * GB), limit("PAGE_CACHE_MAX_ENTRIES", 50_000)),
      );
    }
    this.store = CacheHandler.stores.get(folder);
  }

  /** Path of a response's files without their suffix, in the rendered store. */
  base(key, kind) {
    const suffix = kind === "APP_ROUTE" ? ".body" : ".html";
    return this.rendered.getFilePath(`${key}${suffix}`, kind).slice(0, -suffix.length);
  }

  async get(key, context) {
    if (this.rendered && PERSISTED.has(context?.kind)) {
      const hit = await this.rendered.get(key, context);
      if (hit) {
        this.store.touch(this.base(key, context.kind));
        return hit;
      }
    }
    return this.built.get(key, context);
  }

  async set(key, data, context) {
    const status = data?.status ?? 200;
    // Only successful pages reach the disk: no 404, no error, no redirect.
    if (!this.rendered || !data || !PERSISTED.has(data.kind) || status < 200 || status >= 300) {
      // A page that used to succeed and no longer does (its content was
      // removed): its copy on disk must not keep being served.
      if (this.rendered && data && PERSISTED.has(data.kind)) await this.forget(this.base(key, data.kind));
      // Next's in-memory cache only (bounded), never the disk.
      return this.built.set(key, data, context);
    }
    await this.rendered.set(key, data, context);
    await this.store.add(this.base(key, data.kind), bytesOf(data));
  }

  /** Deletes a page's files on disk and its entry in the store. */
  async forget(base) {
    const bytes = this.store.entries.get(base);
    if (bytes !== undefined) {
      this.store.entries.delete(base);
      this.store.bytes -= bytes;
    }
    await remove(base);
  }

  async revalidateTag(tags, durations) {
    // The tags manifest is shared by every instance.
    return this.built.revalidateTag(tags, durations);
  }

  resetRequestCache() {}
}
