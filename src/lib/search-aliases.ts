/** The other names of a hero in the index of `locale`. */
export function heroAliases(slug: string, locale: Locale): string[] {
  const entry = HERO_ALIASES[slug];
  return entry ? [...(entry.all ?? []), ...(entry[locale] ?? [])] : [];
}
